//! Standard SHA-256 guards over exact source and resource bytes.
use sha2::{Digest, Sha256};
pub fn sha256(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}
