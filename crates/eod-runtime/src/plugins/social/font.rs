pub(super) fn line(character: u8, mut row: i32) -> u8 {
    let Some(index) = character.checked_sub(32) else {
        return 0;
    };
    let Some(glyph) = FONT.get(usize::from(index)) else {
        return 0;
    };
    if glyph[1] & 1 == 1 {
        row -= 1;
    }
    let pixel = match row {
        0 => glyph[0] >> 4,
        1 => glyph[0] >> 1,
        2 => return ((glyph[0] & 3) << 2) | (glyph[1] & 2),
        3 => glyph[1] >> 4,
        4 => glyph[1] >> 1,
        _ => 0,
    };
    pixel & 14
}
